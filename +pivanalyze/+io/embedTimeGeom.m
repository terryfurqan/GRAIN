function embedTimeGeom(matFile, tinfo, geom, includeTable, provenance)
%EMBEDTIMEGEOM  Sematkan waktu EXIF (dt per-frame) + geometri/strain ke .mat.
%
%   pivanalyze.io.embedTimeGeom(matFile, tinfo, geom, includeTable)
%   pivanalyze.io.embedTimeGeom(matFile, tinfo, geom, includeTable, provenance)
%
%   tinfo : keluaran PIVlab_automasi_exiftime ([] = lewati blok waktu).
%   geom  : keluaran pivanalyze.geom.computeGeometry.
%   includeTable : sertakan exif_table penuh bila tersedia.
%
%   Salinan subfungsi embed_time_geom_into_mat dari PIVlab_automasi_batch_V4
%   (tag provenance dapat diubah; default 'pivanalyze_core').

    if nargin < 5 || isempty(provenance); provenance = 'pivanalyze_core'; end
    u = pivanalyze.util.utilities;

    experiment_geometry   = geom;             %#ok<NASGU>
    pivterry_geom_pack    = 'geom_strain_v1'; %#ok<NASGU>
    time_geom_embedded_by = provenance;       %#ok<NASGU>
    vars = {'experiment_geometry', 'pivterry_geom_pack', 'time_geom_embedded_by'};

    if ~isempty(tinfo)
        frame_dt_s     = tinfo.frame_dt_s;       %#ok<NASGU>
        frame_time_s   = tinfo.frame_time_s;     %#ok<NASGU>
        frame_time_abs = tinfo.frame_time_abs;   %#ok<NASGU>
        exif_meta = struct( ...
            'source_dir',  u.dirof(tinfo.exif_file), ...
            'exif_file',   tinfo.exif_file, ...
            'time_field',  tinfo.time_field, ...
            'status',      tinfo.status, ...
            'n_images',    tinfo.n_images, ...
            'n_matched',   tinfo.n_matched, ...
            'nFrames',     tinfo.nFrames, ...
            'n_dt_valid',  tinfo.n_dt_valid, ...
            'n_dt_nan',    tinfo.n_dt_nan, ...
            'dt_median_s', tinfo.dt_median_s, ...
            'dt_mean_s',   tinfo.dt_mean_s, ...
            'message',     tinfo.message, ...
            'embedded_by', provenance, ...
            'units_note',  ['frame_dt_s = detik per pasangan PIV. frame_time_s = ' ...
            'waktu kumulatif (detik) untuk sumbu-X POT.']); %#ok<NASGU>
        pivterry_time_pack = 'exif_time_v1'; %#ok<NASGU>
        vars = [vars, {'frame_dt_s', 'frame_time_s', 'frame_time_abs', ...
            'exif_meta', 'pivterry_time_pack'}];
        if includeTable && istable(tinfo.exif_table) && height(tinfo.exif_table) > 0
            exif_table = tinfo.exif_table; %#ok<NASGU>
            vars = [vars, {'exif_table'}];
        end
    end
    save(matFile, vars{:}, '-append');
end
