    cfg.gridN          = 5;
    cfg.gridColor      = 'w';
    cfg.gridLineWidth  = 2;
    cfg.initMargin     = 0.10;
    cfg.roiPad         = 50;
    cfg.surfMaxRatio   = 0.60;
    cfg.minMatchPts    = 4;
end
